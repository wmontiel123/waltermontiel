(function pixelArt() {
  const canvas = document.getElementById('pixelCanvas');
  if (!canvas) return;
  const ctx = canvas.getContext('2d');

  // Sprite map. Legend:
  //  space = empty   o = outline   b = body   h = highlight
  //  s = shadow      e = eye       a = antenna tip
  const ART = [
    "      aa      ",
    "      bb      ",
    "   oooooooo   ",
    "   obbbbbbo   ",
    "   obhhhhbo   ",
    "   obebbebo   ",
    "   obbbbbbo   ",
    "   obssssbo   ",
    "   oobbbboo   ",
    "    oooooo    ",
    "   oobbbboo   ",
    "  obbhhhhbbo  ",
    "  obbbbbbbbo  ",
    "  obsbbbbsbo  ",
    "  obbbbbbbbo  ",
    "  oob    boo  ",
    "   oo    oo   "
  ];
  const COLS = ART[0].length;
  const ROWS = ART.length;

  const COLORS = {
    o: "#5a4715",
    b: "#d4af37",
    h: "#f5e7a8",
    s: "#9a7b1e",
    e: "#fff8e0",
    a: "#fff3c4"
  };

  let PIXEL = 16;          // size of one sprite pixel (recomputed on resize)
  let twinkles = [];

  function buildTwinkles() {
    twinkles = [];
    const count = 46;
    for (let i = 0; i < count; i++) {
      twinkles.push({
        x: Math.random(),
        y: Math.random(),
        phase: Math.random() * Math.PI * 2,
        speed: 0.6 + Math.random() * 1.4,
        size: Math.random() < 0.5 ? 1 : 2
      });
    }
  }

  function resize() {
    const parent = canvas.parentElement;
    const cssW = Math.min(parent.clientWidth, 260);
    PIXEL = Math.max(7, Math.floor(cssW / (COLS + 6)));
    const w = (COLS + 6) * PIXEL;
    const h = (ROWS + 7) * PIXEL;
    const dpr = window.devicePixelRatio || 1;
    canvas.width = w * dpr;
    canvas.height = h * dpr;
    canvas.style.width = w + 'px';
    canvas.style.height = h + 'px';
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.imageSmoothingEnabled = false;
  }

  function draw(t) {
    const w = canvas.width / (window.devicePixelRatio || 1);
    const h = canvas.height / (window.devicePixelRatio || 1);
    ctx.clearRect(0, 0, w, h);

    // soft radial glow
    const cx = w / 2, cy = h / 2;
    const g = ctx.createRadialGradient(cx, cy, 0, cx, cy, w * 0.55);
    g.addColorStop(0, "rgba(212,175,55,0.10)");
    g.addColorStop(1, "rgba(212,175,55,0)");
    ctx.fillStyle = g;
    ctx.fillRect(0, 0, w, h);

    // twinkling background pixels
    twinkles.forEach(tw => {
      const a = 0.15 + 0.55 * (0.5 + 0.5 * Math.sin(t * 0.001 * tw.speed + tw.phase));
      ctx.fillStyle = `rgba(245,231,168,${a.toFixed(3)})`;
      const px = Math.floor(tw.x * (w - PIXEL));
      const py = Math.floor(tw.y * (h - PIXEL));
      ctx.fillRect(px, py, tw.size * (PIXEL / 2), tw.size * (PIXEL / 2));
    });

    // sprite placement (centered) with gentle float
    const floatY = Math.sin(t * 0.0014) * (PIXEL * 0.55);
    const originX = Math.round((w - COLS * PIXEL) / 2);
    const originY = Math.round((h - ROWS * PIXEL) / 2 + floatY);

    // antenna tip pulse
    const pulse = 0.55 + 0.45 * (0.5 + 0.5 * Math.sin(t * 0.005));
    // blink: closed for a brief window every ~3.4s
    const blink = (t % 3400) < 140;

    for (let r = 0; r < ROWS; r++) {
      for (let c = 0; c < COLS; c++) {
        let ch = ART[r][c];
        if (ch === ' ') continue;
        let color = COLORS[ch];
        if (ch === 'e') {
          if (blink) { color = COLORS.b; }   // eyes closed -> body color
          else {
            const a = (0.7 + 0.3 * Math.sin(t * 0.004)).toFixed(3);
            color = `rgba(255,248,224,${a})`;
          }
        } else if (ch === 'a') {
          // glowing antenna tip
          ctx.save();
          ctx.shadowColor = "rgba(255,243,196,0.9)";
          ctx.shadowBlur = PIXEL * pulse * 1.6;
          ctx.fillStyle = `rgba(255,243,196,${(0.7 + 0.3 * pulse).toFixed(3)})`;
          ctx.fillRect(originX + c * PIXEL, originY + r * PIXEL, PIXEL, PIXEL);
          ctx.restore();
          continue;
        }
        ctx.fillStyle = color;
        ctx.fillRect(originX + c * PIXEL, originY + r * PIXEL, PIXEL, PIXEL);
      }
    }

    requestAnimationFrame(draw);
  }

  buildTwinkles();
  resize();
  window.addEventListener('resize', () => { resize(); buildTwinkles(); });
  requestAnimationFrame(draw);
})();
